package main

import (
	"context"
	"errors"
	"fmt"
	"os"
	"strings"

	"uploader/internal/auth"
	"uploader/internal/db"
	"uploader/internal/db/store"
	"uploader/internal/storage"
	"uploader/internal/upload"
)

// runSeed populates a fresh dev database with a demo admin and a few sample
// uploads. Safe to run repeatedly: it only seeds when no users exist.
func runSeed() error {
	dbURL := os.Getenv("UPLOADER_DATABASE_URL")
	if dbURL == "" {
		return errors.New("UPLOADER_DATABASE_URL is required")
	}
	storageRoot := os.Getenv("UPLOADER_STORAGE_FILE_ROOT")
	if storageRoot == "" {
		storageRoot = "./data/files"
	}
	// `docker compose exec app uploader seed` runs as root. Blobs written as
	// root were unreadable to the server after its own privilege drop, and the
	// next boot did not repair them: it only re-chowns when the data dir itself
	// has the wrong owner.
	if err := dropPrivileges(storageRoot); err != nil {
		return fmt.Errorf("drop privileges: %w", err)
	}

	ctx := context.Background()
	if err := db.Migrate(ctx, dbURL, "up"); err != nil {
		return fmt.Errorf("migrate: %w", err)
	}
	pool, err := db.Connect(ctx, dbURL)
	if err != nil {
		return err
	}
	defer pool.Close()
	st := store.New(pool)

	if n, err := st.CountUsers(ctx); err != nil {
		return err
	} else if n > 0 {
		fmt.Println("seed: users already exist, nothing to do")
		return nil
	}

	hash, err := auth.HashPassword("demo12345")
	if err != nil {
		return err
	}
	if err := st.CreateUser(ctx, store.User{
		Username:     "demo",
		Email:        "demo@example.com",
		PasswordHash: hash,
		IsAdmin:      true,
	}); err != nil {
		return err
	}
	u, err := st.GetUserByUsername(ctx, "demo")
	if err != nil {
		return err
	}

	blobs, err := storage.NewFileStorage(storageRoot)
	if err != nil {
		return err
	}
	uploads := upload.NewService(st, blobs, 6)

	for i := 1; i <= 5; i++ {
		content := fmt.Sprintf("Sample upload #%d — generated by `uploader seed`.\n", i)
		name := fmt.Sprintf("sample-%d.txt", i)
		if _, err := uploads.Save(ctx, u.ID, strings.NewReader(content), name, true); err != nil {
			return fmt.Errorf("seed upload %d: %w", i, err)
		}
	}

	fmt.Println("seed: created admin 'demo' (password 'demo12345') and 5 sample files")
	return nil
}
